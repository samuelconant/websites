export function getPiece(slug: string): Piece | undefined {
  return pieces.find((p) => p.slug === slug);
}

export function getAdjacent(slug: string): { prev?: Piece; next?: Piece } {
  const i = pieces.findIndex((p) => p.slug === slug);
  if (i === -1) return {};
  return { prev: pieces[i - 1], next: pieces[i + 1] };
}
